"""What the console tells someone adding a cluster.

Two cases, because they are set up differently and people mean both when they say
"add a cluster":

* **This machine.** The MARS compose file already defines a second cluster behind
  the ``second-target`` profile, on the console's network. One command starts it.
* **Another machine.** The ``remote-target`` template, rendered into a single
  self-contained compose file: the Flink image pinned to exactly what this
  installation runs, and the Flink configuration inlined, so nothing else needs
  copying.

Both run the same image as the default cluster. Two clusters on different images
can disagree about connectors, which surfaces as a job that works on one and fails
on the other.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

import yaml

from .settings import settings

# Next to the app in the console image (see backend/Dockerfile); at the repository
# root in a checkout.
_APP_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_DIR = next(
    (p for p in (_APP_ROOT / "remote-target", _APP_ROOT.parent / "remote-target") if p.is_dir()),
    _APP_ROOT / "remote-target",
)

SAME_MACHINE_NAME = "mars-b"
SAME_MACHINE_REST = "http://jobmanager-b:8081"
SAME_MACHINE_GATEWAY = "http://sql-gateway-b:8083"
SAME_MACHINE_COMMAND = "docker compose --profile second-target up -d"

# Shown by compose when the variable is missing. Worded from where it is read: on the
# new machine, where "the address MARS reaches" sounded like MARS's own address.
_BIND = (
    "${TARGET_BIND_ADDRESS:?Set TARGET_BIND_ADDRESS to this machine's own IP address "
    "(find it with: hostname -I), not the MARS machine's. "
    "Example: TARGET_BIND_ADDRESS=192.168.1.60 docker compose up -d}"
)


@dataclass
class SetupGuide:
    flink_image: str
    image_pinned: bool
    registry: str | None
    other_machine_compose: str


def flink_image() -> str:
    return settings().flink_image or "mars/flink:0.1.0"


def guide(slots: int | None = None) -> SetupGuide:
    image = flink_image()
    pinned = "@sha256:" in image
    registry = image.split("/", 1)[0] if "." in image.split("/", 1)[0] else None
    return SetupGuide(
        flink_image=image,
        image_pinned=pinned,
        registry=registry,
        other_machine_compose=render_remote_compose(image, slots=slots),
    )


class _Literal(str):
    """A string YAML writes as a literal block, so the inlined config stays readable."""


def _literal(dumper: yaml.Dumper, value: _Literal) -> yaml.Node:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(_Literal, _literal)


def render_remote_compose(
    image: str, template_dir: Path = TEMPLATE_DIR, slots: int | None = None,
) -> str:
    """remote-target/docker-compose.yml, made self-contained.

    The bind-mounted config becomes an inline ``configs`` entry (Docker Compose
    2.23 or newer), the image is pinned, and the bind address must be given: the
    template's default of 127.0.0.1 would leave the console unable to connect,
    which only shows up later as an unreachable cluster.
    """
    compose = yaml.safe_load((template_dir / "docker-compose.yml").read_text())
    config_text = (template_dir / "conf" / "config.yaml").read_text()
    if slots is not None:
        # One slot runs one job at parallelism 1. Edited in place, so the inlined
        # config keeps the template's comments.
        config_text, n = re.subn(
            r"^(\s*numberOfTaskSlots:\s*)\d+", rf"\g<1>{int(slots)}", config_text, flags=re.M,
        )
        if n != 1:
            raise ValueError("The template must set numberOfTaskSlots exactly once.")

    for service in compose["services"].values():
        service["image"] = image
        mounts = service.get("volumes", [])
        kept = [m for m in mounts if not str(m).startswith("./conf/config.yaml:")]
        if len(kept) != len(mounts):
            service["configs"] = [{"source": "flink-config", "target": "/opt/flink/conf/config.yaml"}]
        if kept:
            service["volumes"] = kept
        else:
            service.pop("volumes", None)
        if "ports" in service:
            service["ports"] = [
                str(p).replace("${TARGET_BIND_ADDRESS:-127.0.0.1}", _BIND) for p in service["ports"]
            ]

    compose["configs"] = {"flink-config": {"content": _Literal(config_text)}}

    header = (
        "# A MARS cluster for another machine, generated by the MARS console.\n"
        f"# Image: {image}\n"
        "# Needs Docker Compose 2.23 or newer. Start it with this machine's own IP\n"
        "# address (hostname -I shows it), not the MARS machine's:\n"
        "#   TARGET_BIND_ADDRESS=<this machine's IP> docker compose up -d\n"
        "# MARS needs ports 8081 and 8083 from its own machine. 9249 (JobManager) and\n"
        "# 9250 (TaskManager) serve Prometheus metrics for your monitoring. None is\n"
        "# authenticated: keep them on a trusted network.\n"
    )
    return header + yaml.dump(compose, Dumper=_Dumper, sort_keys=False, width=100)


# -- shared savepoint storage ---------------------------------------------------

SAVEPOINT_MOUNT = "/flink-savepoints"
_HOST = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.-]{0,252}$")
_EXPORT = re.compile(r"^/[A-Za-z0-9._/@+-]{0,1023}$")


def savepoint_override(
    server: str, export: str, clusters: list[tuple[str, str]] | None = None,
) -> str:
    """A docker-compose.override.yml putting a cluster's savepoints on an NFS share.

    Compose reads the override file next to docker-compose.yml by itself, so the
    generated compose file and the MARS one stay as they are. The location is set
    on the JobManager's command line: the config file is mounted read-only, and the
    image's FLINK_PROPERTIES works by rewriting it, so that is silently ignored.
    The TaskManager needs only the mount, since it writes the savepoint's data.

    clusters: (jobmanager, taskmanager) service names, one pair per cluster on the
    machine: ("jobmanager", "taskmanager") for MARS's own cluster and one made by
    the guide, ("jobmanager-b", "taskmanager-b") for the second-target profile.

    NFSv3 needs ``nolock`` here: neither host runs the lock service, and without it
    the mount is refused. Flink does not lock savepoint files.
    """
    if not _HOST.match(server):
        raise ValueError("The NFS server must be a host name or IP address.")
    if not _EXPORT.match(export):
        raise ValueError("The export path must be an absolute path, like /volume1/flink-savepoints.")
    clusters = clusters or [("jobmanager", "taskmanager")]
    services: dict = {}
    for jobmanager, taskmanager in clusters:
        services[jobmanager] = {
            "command": ["jobmanager", "-D", f"state.savepoints.dir=file://{SAVEPOINT_MOUNT}"],
            "volumes": [f"flink-savepoints:{SAVEPOINT_MOUNT}"],
        }
        services[taskmanager] = {"volumes": [f"flink-savepoints:{SAVEPOINT_MOUNT}"]}
    override = {
        "services": services,
        "volumes": {
            "flink-savepoints": {
                "driver": "local",
                "driver_opts": {
                    "type": "nfs",
                    "o": f"addr={server},nfsvers=3,nolock,rw,hard,timeo=600",
                    "device": f":{export}",
                },
            },
        },
    }
    header = (
        "# Shared savepoint storage, generated by the MARS console. Save as\n"
        "# docker-compose.override.yml next to this cluster's docker-compose.yml.\n"
        "# Stop this cluster's jobs with their state saved first, then apply with:\n"
        f"#   docker compose up -d {' '.join(services)}\n"
    )
    return header + yaml.dump(override, Dumper=_Dumper, sort_keys=False, width=100)
